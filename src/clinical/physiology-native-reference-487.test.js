let comparedNumbers = 0;
function withinTolerance(a, b, at = 'reference') {
  if (typeof b === 'number') {
    assert(Number.isFinite(a) && Number.isFinite(b), 'finite numbers at ' + at);
    const tolerance = 1e-8 + Math.abs(b) * 1e-10;
    assert(Math.abs(a - b) <= tolerance, at + ': regenerated ' + a + ', frozen ' + b);
    comparedNumbers++;
    return;
  }
  if (Array.isArray(b)) {
    assert(Array.isArray(a), at + ' array');
    assert.equal(a.length, b.length, at + ' length');
    b.forEach((value, i) => withinTolerance(a[i], value, at + '[' + i + ']'));
    return;
  }
  if (b && typeof b === 'object') {
    assert(a && typeof a === 'object', at + ' object');
    assert.deepEqual(Object.keys(a).sort(), Object.keys(b).sort(), at + ' keys');
    for (const key of Object.keys(b)) withinTolerance(a[key], b[key], at + '.' + key);
    return;
  }
  assert.equal(a, b, at);
}
