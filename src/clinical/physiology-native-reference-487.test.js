  assert(t);
  assert.equal(t.points.length, NATIVE_PILOT_TIMES_487.length);
  assert.deepEqual(t.points[0].vitals, t.initial.vitals, 'orders alone cannot change vitals');
  assert.equal(t.points[0].administrationCount, 0, 'time0 is actual preparation, not administration');
  assert.deepEqual(t.points[0].pending, scenario.orders.map(o => o.id));
  assert.equal(t.administrations.length, scenario.orders.length);
