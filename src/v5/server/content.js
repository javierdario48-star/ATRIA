import map from '../content/hospital.json' with {type:'json'};
import beds from '../content/beds.json' with {type:'json'};
import cases from '../content/cases.json' with {type:'json'};
import therapies from '../content/therapies.json' with {type:'json'};
import defaultDoses from '../content/default-doses.json' with {type:'json'};
import certifiedCatalog from '../content/certified-case-packs.json' with {type:'json'};
import {readCertifiedCaseCatalog} from '../content/certified-case-catalog.js';
import {createClinicalContent} from '../content/clinical-content.js';
import {CLINICAL_POLICY_REGISTRIES} from '../clinical/clinical-policy-registry.js';
const catalog=readCertifiedCaseCatalog(certifiedCatalog,{...CLINICAL_POLICY_REGISTRIES,existingCaseIds:cases.map(c=>c.id)});
if(!catalog.ok)throw Error('Uncertified clinical catalog: '+catalog.errors.join('; '));
export const clinicalContent=createClinicalContent({map,beds,cases,therapies,defaultDoses},{additionalCases:catalog.cases});
